# النوع والعائلة و«الخارج عن العائلة» يرثون ما لأبيهم؛ والاسم الآخر يُحال إلى مسمّاه (وراثةٌ بالإحالة).
# الطريق يحفظ اسم الأب كما كُتب (بيت=مسكن).
amap = {}
for r in T["NODES"]:
    # الإحالة في الطريق تتبع الاسم الآخر المطلق وحده؛ المقيّد بقولٍ يبقى حافّةَ إحالة ولا يدمج العقدتين.
    if r["node_type"] == "اسم آخر" and r["qawl"] == MT: amap.setdefault(r["node"], set()).add(r["parent"])
def canon(n):
    seen = set()
    while n in amap and len(amap[n]) == 1:
        assert n not in seen; seen.add(n); n = next(iter(amap[n]))
    return n
def lab(n):
    c = canon(n)
    return n if c == n else f"{n}(={c})"
edges = {}   # canon parent -> list of (child, label, qawl, kind)
for r in T["NODES"]:
    t = r["node_type"]
    if t in ("نوع", "عائلة", "خارج العائلة"):
        edges.setdefault(canon(r["parent"]), []).append((r["node"], lab(r["parent"]), r["qawl"], "وراثة"))
    elif t == "اسم آخر":
        edges.setdefault(canon(r["parent"]), []).append((r["node"], lab(r["parent"]), r["qawl"], "إحالة"))
def under(f, path, qs, depth=0):
    assert depth < 12
    for k, pl, q, kind in sorted(edges.get(f, ())):
        q2 = qs + ([q] if q != MT else [])
        p2 = path[:-1] + [pl if "=" in pl else path[-1], k]
        yield k, p2, q2, kind
        if kind == "وراثة":
            yield from under(k, p2, q2, depth + 1)
groups = {}
for a in T["ATTACH"]:
    groups.setdefault((a["event"], a["family"], a["role"], a["qawl"]), []).append(a["rid"])
for (ev, fam, role, aq), rids in groups.items():
    for n, path, qs, kind in under(canon(fam), [fam], []):
        qs2 = ([aq] if aq != MT else []) + qs
        T["INHERIT"].append(dict(event=ev, role=role, node=n, kind=kind,
                                  via=" ← ".join(reversed(path)), qawl="؛ ".join(qs2) or MT, by=",".join(rids)))

