def span(L, a, b):
    t = " ".join(re.sub(r"\s*ms\d+\s*", " ", x.lstrip("#~ $")).strip() for x in L[a-1:b] if not x.startswith("# PageV"))
    return re.sub(r"\s+", " ", t)
def cite(k, a, quote):
    """أصغر مدى يحوي المقتبس حول السطر المعطى (±6)."""
    L = lines(k); best = None
    for x in range(max(1, a-6), a+7):
        for y in range(x, x+8):
            if quote in span(L, x, y):
                if best is None or (y-x) < (best[1]-best[0]): best = (x, y)
                break
    assert best, (k, a, quote)
    a, b = best
    if k == "lisan":
        mad = next(re.match(r"### \$\s*(\S+?):", L[i]).group(1) for i in range(a-1, -1, -1) if L[i].startswith("### $"))
        ms = next((m[-1] for i in range(b-1, -1, -1) for m in [re.findall(r"ms\d+", L[i])] if m), "")
        return quote, f"{SRC[k][1]} — مادّة «{mad}»، سطر {a}–{b}، بعد الوسم {ms}"
    pg = next((x.strip("# ") for x in L[b:] if x.startswith("# PageV")), "")
    return quote, f"{SRC[k][1]} — سطر {a}–{b}، قبل {pg}"
