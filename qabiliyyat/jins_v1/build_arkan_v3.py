# الاسم الآخر يُحال إلى مسمّاه؛ والنوع يرث ما لأبيه بعد الإحالة.
alias = {r["node"]: r["parent"] for r in T["NODES"] if r["node_type"] == "اسم آخر"}
def canon(n):
    while n in alias: n = alias[n]
    return n
kids, qw = {}, {}
for r in T["NODES"]:
    if r["node_type"] == "نوع":
        kids.setdefault(canon(r["parent"]), set()).add(r["node"]); qw[r["node"]] = r["qawl"]
def under(f, path):
    for k in sorted(kids.get(f, ())):
        yield k, path + [k]
        yield from under(k, path + [k])
seen = set()
for a in T["ATTACH"]:
    key = (a["event"], a["family"], a["role"])
    if key in seen: continue
    seen.add(key)
    for n, path in under(canon(a["family"]), [a["family"]]):
        T["INHERIT"].append(dict(event=a["event"], role=a["role"], node=n, via=" ← ".join(reversed(path)),
                                  qawl="على قول" if any(qw.get(p) == "على قول" for p in path) else "مطلق",
                                  by=",".join(x["rid"] for x in T["ATTACH"] if (x["event"], x["family"], x["role"]) == key)))

